const locale = window.location.pathname.split('/').includes('en-us') ? 'en-US' : 'pt-BR';
document.documentElement.lang = locale;

function t(message, values = {}) {
  const localized = locale === 'en-US' ? (EN_US[message] ?? message) : message;
  return localized.replace(new RegExp('\\{(\\w+)\\}', 'g'), (match, key) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
}

function translateStaticContent() {
  if (locale !== 'en-US') return;

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement?.closest('script, style')) continue;
    const value = node.nodeValue;
    const trimmed = value.trim();
    if (!trimmed || !Object.prototype.hasOwnProperty.call(EN_US, trimmed)) continue;
    node.nodeValue = value.replace(trimmed, EN_US[trimmed]);
  }

  for (const element of document.querySelectorAll('[aria-label], [alt], [title]')) {
    for (const attribute of ['aria-label', 'alt', 'title']) {
      const value = element.getAttribute(attribute);
      if (value && EN_US[value]) element.setAttribute(attribute, EN_US[value]);
    }
  }

  document.title = t(document.title);
  const metaDescription = document.querySelector('meta[name="description"]');
  if (metaDescription) metaDescription.content = t(metaDescription.content);
}

